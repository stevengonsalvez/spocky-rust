#!/usr/bin/env node
// Generates crates/spocky-contracts/src/js_locale_tables.rs: the canonical
// combining classes of Unicode 16.0.0, the version of the ICU 77.1 inside
// node v22.20.0. The locale-sensitive lowercasing of Turkic and Lithuanian
// text (spocky_contracts::locale) tests combining classes 0 and 230 around
// `I`, `J`, `Į`, and U+0307, and ICU reads them from this data.
//
// Usage (Node 22.20.0, the binary pinned by the slice harness):
//   ~/.nvm/versions/node/v22.20.0/bin/node scripts/phase3/contracts-locale-tables.mjs \
//     --ucd <DerivedCombiningClass.txt of Unicode 16.0.0> [--check]
//
// The file is https://www.unicode.org/Public/16.0.0/ucd/extracted/DerivedCombiningClass.txt
// and must have the SHA-256 pinned below. --check regenerates in memory and
// exits 1 if the committed file differs.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const NODE_VERSION = "v22.20.0";
const UCD_SHA256 = "52064d588c98c623b2373905e6a449eb520f900113954bcd212e94ef0810b471";
const here = dirname(fileURLToPath(import.meta.url));
const outputPath = join(resolve(here, "../.."), "crates/spocky-contracts/src/js_locale_tables.rs");

function fail(message) {
  process.stderr.write(`contracts-locale-tables: ${message}\n`);
  process.exit(2);
}

const args = process.argv.slice(2);
let ucdPath = null;
let check = false;
for (let index = 0; index < args.length; index += 1) {
  if (args[index] === "--ucd") ucdPath = args[++index];
  else if (args[index] === "--check") check = true;
  else fail(`unknown argument ${args[index]}`);
}
if (!ucdPath) fail("--ucd <DerivedCombiningClass.txt> is required");
if (process.version !== NODE_VERSION) fail(`expected node ${NODE_VERSION}, running ${process.version}`);
if (process.versions.unicode !== "16.0") fail(`node reports Unicode ${process.versions.unicode}, expected 16.0`);

const bytes = readFileSync(resolve(ucdPath));
const digest = createHash("sha256").update(bytes).digest("hex");
if (digest !== UCD_SHA256) fail(`${ucdPath} has SHA-256 ${digest}, not ${UCD_SHA256}`);

// Lines are `0300..0314    ; 230 # Mn  [21] COMBINING GRAVE ACCENT..`; class 0 is the default.
const ranges = [];
for (const line of bytes.toString("utf8").split("\n")) {
  const match = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\d+)\s*#/.exec(line);
  if (!match) continue;
  const first = parseInt(match[1], 16);
  const last = match[2] === undefined ? first : parseInt(match[2], 16);
  const combiningClass = Number(match[3]);
  if (combiningClass !== 0) ranges.push([first, last, combiningClass]);
}
ranges.sort((left, right) => left[0] - right[0]);

const values = ranges.flat();
let text = `// Generated by scripts/phase3/contracts-locale-tables.mjs; do not edit.
//! Canonical combining classes of Unicode 16.0.0 (node v22.20.0, ICU 77.1) for
//! [\`crate::locale\`], from \`DerivedCombiningClass.txt\` (SHA-256 \`${UCD_SHA256}\`).

// Data copied from the UCD keeps its literals as the UCD writes them.
#![allow(clippy::unreadable_literal)]

/// \`(first, last, class)\` triples, flattened and sorted, for every code point
/// whose canonical combining class is not 0.
pub static COMBINING_CLASS_RANGES: [u32; ${values.length}] = [
`;
for (let index = 0; index < values.length; index += 12) {
  text += `    ${values.slice(index, index + 12).join(", ")},\n`;
}
text += "];\n";

if (check) {
  if (readFileSync(outputPath, "utf8") !== text) {
    process.stderr.write("contracts-locale-tables: js_locale_tables.rs is stale; rerun without --check\n");
    process.exit(1);
  }
  process.stdout.write(`contracts-locale-tables: ${outputPath} is current\n`);
} else {
  writeFileSync(outputPath, text);
  process.stdout.write(`contracts-locale-tables: wrote ${outputPath} (${ranges.length} ranges)\n`);
}
